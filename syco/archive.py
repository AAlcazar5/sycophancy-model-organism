"""Archive the raw run outputs in results/ that git does not track (replies and stance labels, ~86 MB).

    bundle   the shareable files as a tarball for Zenodo, with a sha256 manifest and a README
    push     every file to a private Hugging Face dataset; refuses a repo that is not private

    python -m syco.archive bundle --out ~/zenodo_upload
    python -m syco.archive push --repo <user>/sycophancy-organism-raw

SycophancyEval has no license, so files built on it stay out of the public bundle; so do the internal results
store, the spend ledger and pod snapshots.
"""
from __future__ import annotations

import argparse
import json
import tarfile
from pathlib import Path
from typing import Any

from syco import paths
from syco.repro import file_sha256, git_sha

UNLICENSED_MARKER = "syco_eval_"
INTERNAL_NAMES = frozenset({"results.db", "spend_ledger.jsonl"})
INTERNAL_DIR_PREFIX = "pod_"

PRIVATE_README = """# Sycophancy model organism: raw results (PRIVATE)

Every file in `results/` at git commit `{sha}`. It includes replies built on SycophancyEval (Sharma et al., 2023),
which has no license: **never make this dataset public.** The shareable subset is archived on Zenodo.
"""


def is_shareable(rel: Path) -> bool:
    """True for a results/-relative path that may go in the public archive."""
    if UNLICENSED_MARKER in rel.name or rel.name in INTERNAL_NAMES:
        return False
    return not any(part.startswith(INTERNAL_DIR_PREFIX) for part in rel.parts[:-1])


def result_files(results_dir: Path) -> list[Path]:
    """Every non-hidden file under results_dir, relative to it, sorted."""
    return sorted(p.relative_to(results_dir) for p in results_dir.rglob("*")
                  if p.is_file() and not any(part.startswith(".") for part in p.relative_to(results_dir).parts))


def manifest(results_dir: Path, files: list[Path]) -> dict[str, Any]:
    rows = [{"path": f"results/{rel.as_posix()}", "bytes": (results_dir / rel).stat().st_size,
             "sha256": file_sha256(results_dir / rel)} for rel in files]
    return {"git_sha": git_sha(), "files": rows}


def public_readme(sha: str, kept: list[Path], left_out: list[Path]) -> str:
    excluded = "\n".join(f"- `{rel.as_posix()}`" for rel in left_out if UNLICENSED_MARKER in rel.name)
    return f"""# Sycophancy model organism: raw results

Replies and stance labels behind the analyses at git commit `{sha}`: {len(kept)} files, listed with their sha256
in `MANIFEST.json`. `results/runs.csv` in the repository records each run's `output_sha256`, which matches the
manifest. Replies were generated by `google/gemma-2-2b-it` (see the Gemma Terms of Use) and labelled by
`claude-haiku-4-5`; the items are the repository's own audited sets and SYCON-Bench (Hong et al., 2025; MIT).

## Left out

SycophancyEval (Sharma et al., 2023) has no license, so replies built on its prompts are not redistributed.
Download the benchmark with `python -m syco.data.benchmarks` and re-run the evaluation to rebuild them:

{excluded or "- none"}

The internal results store, the spend ledger and pod snapshots are also left out.
"""


def bundle(results_dir: Path, out_dir: Path) -> Path:
    """Write MANIFEST.json, README.md and a tarball of the shareable files (plus both) into out_dir."""
    files = result_files(results_dir)
    kept = [rel for rel in files if is_shareable(rel)]
    left_out = [rel for rel in files if not is_shareable(rel)]
    record = manifest(results_dir, kept)
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "MANIFEST.json").write_text(json.dumps(record, indent=2) + "\n")
    (out_dir / "README.md").write_text(public_readme(record["git_sha"], kept, left_out))
    tar_path = out_dir / f"sycophancy_organism_results_{record['git_sha'][:12]}.tar.gz"
    with tarfile.open(tar_path, "w:gz") as tar:
        for name in ("README.md", "MANIFEST.json"):
            tar.add(out_dir / name, arcname=name)
        for rel in kept:
            tar.add(results_dir / rel, arcname=f"results/{rel.as_posix()}")
    return tar_path


def push_private(results_dir: Path, repo_id: str, api: Any = None) -> None:
    """Upload every file in results_dir to a private dataset repo, after checking the repo really is private."""
    if api is None:
        from huggingface_hub import HfApi
        api = HfApi()
    api.create_repo(repo_id, repo_type="dataset", private=True, exist_ok=True)
    if not api.repo_info(repo_id, repo_type="dataset").private:
        raise SystemExit(f"{repo_id} is not private; refusing to upload SycophancyEval-derived files to it")
    sha = git_sha()
    api.upload_file(path_or_fileobj=PRIVATE_README.format(sha=sha).encode(), path_in_repo="README.md",
                    repo_id=repo_id, repo_type="dataset")
    api.upload_folder(folder_path=results_dir, path_in_repo="results", repo_id=repo_id, repo_type="dataset",
                      ignore_patterns=[".*", "**/.*"], commit_message=f"results at {sha}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = parser.add_subparsers(dest="command", required=True)
    bundle_cmd = sub.add_parser("bundle", help="tarball of the shareable files for Zenodo")
    bundle_cmd.add_argument("--out", type=Path, required=True)
    push_cmd = sub.add_parser("push", help="every file to a private Hugging Face dataset")
    push_cmd.add_argument("--repo", required=True, help="<user>/<dataset name>")
    parser.add_argument("--results-dir", type=Path, default=paths.RESULTS_DIR)
    args = parser.parse_args()
    if args.command == "bundle":
        print("wrote", bundle(args.results_dir, args.out.expanduser()))
    else:
        push_private(args.results_dir, args.repo)
        print(f"pushed {args.results_dir} to https://huggingface.co/datasets/{args.repo} (private)")


if __name__ == "__main__":
    main()
